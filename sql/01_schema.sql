CREATE TABLE dim_customer (
  customer_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  VARCHAR2(50),
  customer_name VARCHAR2(100),
  customer_email VARCHAR2(100),
  phone        VARCHAR2(20),
  age          NUMBER,
  age_group    VARCHAR2(20),
  gender       VARCHAR2(10),
  city         VARCHAR2(50)
);

CREATE TABLE dim_movie (
  movie_key    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movie_title  VARCHAR2(150),
  genre        VARCHAR2(50),
  language     VARCHAR2(30)
);

CREATE TABLE dim_show (
  show_key     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  screen       VARCHAR2(20),
  format       VARCHAR2(10),
  show_date    DATE,
  show_time    VARCHAR2(10),
  show_datetime DATE
);

CREATE TABLE dim_date (
  date_key     NUMBER PRIMARY KEY,
  full_date    DATE,
  day_of_week  VARCHAR2(10),
  day_name     VARCHAR2(10),
  month        NUMBER,
  month_name   VARCHAR2(10),
  quarter      NUMBER,
  year         NUMBER,
  is_weekend   VARCHAR2(3)
);

CREATE TABLE dim_payment (
  payment_key      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_method   VARCHAR2(20),
  booking_channel  VARCHAR2(20)
);

CREATE TABLE fact_bookings (
  booking_fact_key NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id       VARCHAR2(20),
  customer_key     NUMBER REFERENCES dim_customer(customer_key),
  movie_key        NUMBER REFERENCES dim_movie(movie_key),
  show_key         NUMBER REFERENCES dim_show(show_key),
  date_key         NUMBER REFERENCES dim_date(date_key),
  payment_key      NUMBER REFERENCES dim_payment(payment_key),
  seats            NUMBER,
  ticket_price     NUMBER,
  convenience_fee  NUMBER,
  discount_amount  NUMBER,
  total_amount     NUMBER,
  promo_code       VARCHAR2(30),
  booking_status   VARCHAR2(20),
  booking_datetime DATE
);

CREATE INDEX idx_fact_customer ON fact_bookings(customer_key);
CREATE INDEX idx_fact_movie ON fact_bookings(movie_key);
CREATE INDEX idx_fact_date ON fact_bookings(date_key);
CREATE INDEX idx_fact_status ON fact_bookings(booking_status);

